// Migration tooling for @budget-lens/db (see packages/db/README.md).
//
//   node scripts/migrations.mjs generate [--name <slug>]  drizzle-kit generate, then write the TS bundle
//   node scripts/migrations.mjs check                     guards run by `pnpm lint` (and so by `pnpm check` and CI)
//
// The bundle (src/migrations.generated.ts) has the `{ journal, migrations }` shape that Drizzle's expo migrator
// reads, so the app needs no Babel inline-import plugin and no `.sql` Metro extension (#35).
import { spawnSync } from "node:child_process";
import {
  cpSync,
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = "drizzle";
const SCHEMA = "./src/schema.ts";
const MODULE = join(root, "src", "migrations.generated.ts");
const drizzleKit = join(root, "node_modules", ".bin", "drizzle-kit");

function readJournal(folder) {
  return JSON.parse(readFileSync(join(root, folder, "meta", "_journal.json"), "utf8"));
}

function renderModule() {
  const journal = readJournal(OUT);
  const migrations = Object.fromEntries(
    journal.entries.map((entry) => [
      `m${String(entry.idx).padStart(4, "0")}`,
      readFileSync(join(root, OUT, `${entry.tag}.sql`), "utf8"),
    ]),
  );
  const bundle = {
    journal: {
      entries: journal.entries.map(({ idx, when, tag, breakpoints }) => ({
        idx,
        when,
        tag,
        breakpoints,
      })),
    },
    migrations,
  };
  return [
    "// Generated by packages/db/scripts/migrations.mjs from packages/db/drizzle. Do not edit:",
    "// change src/schema.ts and run `pnpm --filter @budget-lens/db db:generate --name <slug>`.",
    'import type { MigrationBundle } from "./migration-bundle";',
    "",
    `const bundle: MigrationBundle = ${JSON.stringify(bundle, null, 2)};`,
    "",
    "export default bundle;",
    "",
  ].join("\n");
}

function drizzle(args) {
  const result = spawnSync(drizzleKit, args, { cwd: root, encoding: "utf8" });
  return { status: result.status, output: `${result.stdout ?? ""}${result.stderr ?? ""}` };
}

function generate(args) {
  const result = spawnSync(drizzleKit, ["generate", ...args], { cwd: root, stdio: "inherit" });
  if (result.status !== 0) process.exit(result.status ?? 1);
  writeFileSync(MODULE, renderModule());
  process.stdout.write(`Wrote ${MODULE.slice(root.length + 1)}\n`);
}

/** Position and ordering problems of one journal entry. */
function orderProblems(entry, position, previous) {
  const problems = [];
  if (entry.idx !== position) {
    problems.push(`journal entry ${entry.tag} has idx ${entry.idx}, expected ${position}`);
  }
  // Drizzle applies only entries newer than the last applied `when` (drizzle-orm #5769), so an older entry after
  // a newer one would never run on devices that already have the newer one.
  if (previous !== undefined && entry.when <= previous.when) {
    problems.push(
      `migration ${entry.tag} (when ${entry.when}) is not newer than ${previous.tag} (when ${previous.when}); ` +
        "delete it and regenerate it on top of the latest migrations",
    );
  }
  return problems;
}

/** Problems of the SQL file of one journal entry. */
function fileProblems(entry) {
  const file = join(root, OUT, `${entry.tag}.sql`);
  if (!existsSync(file)) return [`missing ${OUT}/${entry.tag}.sql`];
  // drizzle-kit copies CHECK and partial-index SQL verbatim into `__new_<table>` rebuilds, where a
  // table-qualified `"table"."column"` fails with "no such column".
  if (!/"\w+"\."\w+"/.test(readFileSync(file, "utf8"))) return [];
  return [
    `${OUT}/${entry.tag}.sql has a table-qualified column in a CHECK or index; table rebuilds would fail`,
  ];
}

/** Problems with the journal and SQL files; empty when everything is consistent. */
function journalProblems() {
  const { entries } = readJournal(OUT);
  const problems = entries.flatMap((entry, position) => [
    ...orderProblems(entry, position, entries[position - 1]),
    ...fileProblems(entry),
  ]);
  const tags = new Set(entries.map((entry) => `${entry.tag}.sql`));
  const untracked = readdirSync(join(root, OUT)).filter(
    (name) => name.endsWith(".sql") && !tags.has(name),
  );
  return [...problems, ...untracked.map((file) => `${OUT}/${file} is not in the journal`)];
}

/** Generates into a scratch copy of the migrations folder: any new entry means src/schema.ts is ahead of it. */
function schemaDrift() {
  const scratch = join("node_modules", ".cache", "drizzle-check");
  rmSync(join(root, scratch), { recursive: true, force: true });
  mkdirSync(join(root, scratch), { recursive: true });
  cpSync(join(root, OUT), join(root, scratch), { recursive: true });
  const result = drizzle(["generate", "--dialect", "sqlite", "--schema", SCHEMA, "--out", scratch]);
  const before = readJournal(OUT).entries.length;
  const after = existsSync(join(root, scratch, "meta", "_journal.json"))
    ? readJournal(scratch).entries.length
    : -1;
  rmSync(join(root, scratch), { recursive: true, force: true });
  if (after === before) return [];
  return [`src/schema.ts has changes without a migration; run db:generate\n${result.output}`];
}

function drizzleKitProblems() {
  const kit = drizzle(["check"]);
  const clean = kit.status === 0 && kit.output.includes("Everything's fine");
  return clean ? [] : [`drizzle-kit check failed\n${kit.output}`];
}

function bundleProblems() {
  const current = existsSync(MODULE) && readFileSync(MODULE, "utf8") === renderModule();
  return current ? [] : ["src/migrations.generated.ts is out of date; run db:generate"];
}

function check() {
  const problems = [
    ...journalProblems(),
    ...drizzleKitProblems(),
    ...schemaDrift(),
    ...bundleProblems(),
  ];
  if (problems.length > 0) {
    process.stderr.write(`Migration check failed:\n${problems.map((p) => `- ${p}`).join("\n")}\n`);
    process.exit(1);
  }
  process.stdout.write(
    "Migrations OK: drizzle-kit check clean, journal ordered, bundle up to date.\n",
  );
}

const [command, ...args] = process.argv.slice(2);
if (command === "generate") generate(args);
else if (command === "check") check();
else {
  process.stderr.write("Usage: migrations.mjs generate [--name <slug>] | check\n");
  process.exit(2);
}
